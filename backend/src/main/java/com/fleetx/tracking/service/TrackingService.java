    @Transactional(readOnly = true)
    public String exportReportCsv(
            String reportType,
            LocalDate startDate,
            LocalDate endDate,
            String status
    ) {
        ReportSummaryDto report = getReportSummary(reportType, startDate, endDate, status);
        StringBuilder csv = new StringBuilder();

        // Header line
        csv.append(String.join(",", report.columns())).append("\r\n");

        // Data rows
        for (Map<String, Object> row : report.rows()) {
            List<String> escapedCells = new ArrayList<>(report.columns().size());
            for (String col : report.columns()) {
                escapedCells.add(escapeCsvField(row.get(col)));
            }
            csv.append(String.join(",", escapedCells)).append("\r\n");
        }
        return csv.toString();
    }

    /**
     * RFC 4180 compliant CSV cell escaping with formula-injection protection.
     */
    public String escapeCsvField(Object rawValue) {
        if (rawValue == null) {
            return "";
        }
        String str = String.valueOf(rawValue);
        if (str.isEmpty()) {
            return "";
        }

        // Prevent spreadsheet formula injection (=, +, -, @, tab, CR) on non-numeric strings
        char first = str.charAt(0);
        boolean isFormulaTrigger = (first == '=' || first == '+' || first == '-' || first == '@' || first == '\t' || first == '\r')
                && !(rawValue instanceof Number)
                && !str.matches("^-[0-9]+(\\.[0-9]+)?$");
        if (isFormulaTrigger) {
            str = "'" + str;
        }

        boolean mustQuote = str.contains(",") || str.contains("\"") || str.contains("\n") || str.contains("\r") || isFormulaTrigger;
        if (mustQuote) {
            return "\"" + str.replace("\"", "\"\"") + "\"";
        }
        return str;
    }

