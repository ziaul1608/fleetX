    @Transactional
    public GeofenceResponseDto createGeofence(GeofenceCreateRequest request) {
        mathService.validateCoordinates(request.centerLatitude(), request.centerLongitude());
        if (request.radiusMeters() == null || request.radiusMeters() <= 0) {
            throw new DomainException("Geofence radius in meters must be strictly positive.", HttpStatus.BAD_REQUEST, "INVALID_GEOFENCE_RADIUS");
        }

        String normalizedName = request.name().trim();
        if (geofenceRepository.existsByTenantIdAndNameIgnoreCase(currentTenant(), normalizedName)) {
            throw new ResourceConflictException("A geofence named '" + normalizedName + "' already exists.");
        }

        String fenceType = request.fenceType() != null ? request.fenceType().trim().toUpperCase() : "DEPOT";
        if (!ALLOWED_FENCE_TYPES.contains(fenceType)) {
            throw new DomainException(
                    "Invalid fenceType '" + request.fenceType() + "'. Allowed: " + ALLOWED_FENCE_TYPES,
                    HttpStatus.BAD_REQUEST,
                    "INVALID_FENCE_TYPE"
            );
        }

        String shapeType = (request.shapeType() != null && !request.shapeType().isBlank())
                ? request.shapeType().trim().toUpperCase()
                : "CIRCLE";
        if (!ALLOWED_SHAPE_TYPES.contains(shapeType)) {
            throw new DomainException(
                    "Invalid shapeType '" + request.shapeType() + "'. Allowed: " + ALLOWED_SHAPE_TYPES,
                    HttpStatus.BAD_REQUEST,
                    "INVALID_SHAPE_TYPE"
            );
        }

        String polygonJson = null;
        if ("POLYGON".equals(shapeType)) {
            if (request.polygonCoordinates() == null || request.polygonCoordinates().size() < 3) {
                throw new DomainException(
                        "A POLYGON geofence requires at least 3 vertex coordinate pairs [lat, lng].",
                        HttpStatus.BAD_REQUEST,
                        "INVALID_POLYGON_GEOFENCE"
                );
            }
            for (List<Double> vertex : request.polygonCoordinates()) {
                if (vertex == null || vertex.size() < 2) {
                    throw new DomainException("Each polygon vertex must contain [latitude, longitude].", HttpStatus.BAD_REQUEST, "INVALID_POLYGON_VERTEX");
                }
                mathService.validateCoordinates(vertex.get(0), vertex.get(1));
            }
            try {
                polygonJson = objectMapper.writeValueAsString(request.polygonCoordinates());
            } catch (Exception e) {
                throw new DomainException("Failed to serialize polygon coordinates.", HttpStatus.BAD_REQUEST, "INVALID_POLYGON_JSON");
            }
        }

        Geofence geofence = new Geofence();
        geofence.setTenantId(currentTenant());
        geofence.setName(normalizedName);
        geofence.setCenterLatitude(request.centerLatitude());
        geofence.setCenterLongitude(request.centerLongitude());
        geofence.setRadiusMeters(request.radiusMeters());
        geofence.setFenceType(fenceType);
        geofence.setShapeType(shapeType);
        geofence.setPolygonCoordinatesJson(polygonJson);
        geofence.setSpeedLimitKmh(request.speedLimitKmh());
        geofence.setActive(true);
        geofence.setCreatedAt(Instant.now());

        Geofence saved = geofenceRepository.save(geofence);
        return toGeofenceDto(saved);
    }

