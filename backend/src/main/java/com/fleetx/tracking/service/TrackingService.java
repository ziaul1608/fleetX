    @Transactional
    public AlertResponseDto publishAlertInternal(
            Long tenantId,
            String alertType,
            String severity,
            String entityType,
            Long entityId,
            Long geofenceId,
            String description,
            Instant timestamp
    ) {
        String normType = (alertType != null && !alertType.isBlank()) ? alertType.trim().toUpperCase() : "OPERATIONAL_ALERT";
        String normSeverity = (severity != null && ALLOWED_SEVERITIES.contains(severity.trim().toUpperCase()))
                ? severity.trim().toUpperCase()
                : "WARNING";
        String normEntity = (entityType != null && !entityType.isBlank()) ? entityType.trim().toUpperCase() : "SYSTEM";
        Long safeEntityId = entityId != null ? entityId : 0L;
        Instant eventTime = timestamp != null ? timestamp : Instant.now();
        String safeMessage = (description != null && !description.isBlank()) ? description.trim() : normType;

        String dedupKey = normType + ":" + normEntity + ":" + safeEntityId + ":" + (geofenceId != null ? geofenceId : "0");

        // Deduplicate repeated unacknowledged conditions
        Optional<Alert> existingUnack = alertRepository.findFirstByTenantIdAndDedupKeyAndAcknowledgedFalseOrderByCreatedAtDesc(tenantId, dedupKey);
        if (existingUnack.isPresent()) {
            log.debug("Suppressing duplicate unacknowledged alert for key {}", dedupKey);
            return toAlertDto(existingUnack.get());
        }

        Alert alert = new Alert();
        alert.setTenantId(tenantId);
        alert.setAlertType(normType);
        alert.setSeverity(normSeverity);
        alert.setEntityType(normEntity);
        alert.setEntityId(safeEntityId);
        alert.setGeofenceId(geofenceId);
        alert.setMessage(safeMessage);
        alert.setAcknowledged(false);
        alert.setDedupKey(dedupKey);
        alert.setCreatedAt(eventTime);

        Alert saved = alertRepository.save(alert);

        log.warn("[REAL ALERT] Type: {} | Severity: {} | Entity: {} #{} | Details: {} | At: {}",
                normType, normSeverity, normEntity, safeEntityId, safeMessage, eventTime);

        AlertResponseDto dto = toAlertDto(saved);
        try {
            Long alertTenantId = saved.getTenantId() != null ? saved.getTenantId() : tenantId;
            if (alertTenantId != null) {
                messagingTemplate.convertAndSend("/topic/tenants/" + alertTenantId + "/alerts", dto);
            }
            if (alertTenantId == null || alertTenantId == 1L) {
                messagingTemplate.convertAndSend("/topic/alerts", dto);
            }
        } catch (Exception ex) {
            log.warn("STOMP alert broadcast encountered non-fatal error: {}", ex.getMessage());
        }
        return dto;
    }

