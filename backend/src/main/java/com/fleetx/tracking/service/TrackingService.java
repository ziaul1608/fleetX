    @Transactional
    public SimulatorSessionDto startSimulation(SimulatorStartRequest request) {
        Long vehicleId = request != null ? request.vehicleId() : null;
        Long tripId = request != null ? request.tripId() : null;

        if (tripId != null) {
            final Long requestedTripId = tripId;
            TripSummaryDto trip = tripLookupService.findTripSummaryById(requestedTripId)
                    .orElseThrow(() -> new ResourceNotFoundException("Trip #" + requestedTripId + " not found for simulation."));
            if ("CANCELLED".equalsIgnoreCase(trip.status()) || "COMPLETED".equalsIgnoreCase(trip.status())) {
                throw new DomainException(
                        "Cannot start GPS simulation for Trip #" + tripId + " in terminal status " + trip.status() + ".",
                        HttpStatus.BAD_REQUEST,
                        "INELIGIBLE_TRIP_FOR_SIMULATION"
                );
            }
            if (vehicleId == null) {
                vehicleId = trip.vehicleId();
            }
        }

        if (vehicleId == null) {
            throw new DomainException(
                    "Either a valid vehicleId or tripId must be provided to start simulated GPS tracking.",
                    HttpStatus.BAD_REQUEST,
                    "VEHICLE_OR_TRIP_REQUIRED"
            );
        }

        final Long targetVehicleId = vehicleId;
        VehicleSummaryDto vehicle = vehicleLookupService.findVehicleSummaryById(targetVehicleId)
                .orElseThrow(() -> new ResourceNotFoundException("Vehicle #" + targetVehicleId + " not found for simulation."));

        if ("MAINTENANCE".equalsIgnoreCase(vehicle.status()) || "RETIRED".equalsIgnoreCase(vehicle.status())) {
            throw new DomainException(
                    "Vehicle " + vehicle.licensePlate() + " is in status " + vehicle.status() + " and cannot run simulated transit.",
                    HttpStatus.BAD_REQUEST,
                    "INELIGIBLE_VEHICLE_FOR_SIMULATION"
            );
        }

        if (tripId == null) {
            tripId = readRepository.findActiveTripIdForVehicle(targetVehicleId).orElse(null);
        }

        int tickInterval = (request != null && request.tickIntervalSeconds() != null)
                ? Math.max(1, Math.min(60, request.tickIntervalSeconds()))
                : 2;
        double speedMultiplier = (request != null && request.speedMultiplier() != null)
                ? Math.max(0.5, Math.min(20.0, request.speedMultiplier()))
                : 1.0;
        double baseSpeedKmh = (request != null && request.baseSpeedKmh() != null)
                ? Math.max(0.0, Math.min(250.0, request.baseSpeedKmh()))
                : 62.0;

        List<SimulatorWaypointDto> routeWaypoints = resolveSimulationWaypoints(request != null ? request.waypoints() : null, tripId);

        // Cancel any pre-existing scheduled task for this vehicle to prevent unbounded task creation
        cancelScheduledTaskForVehicle(targetVehicleId);

        SimulatorWaypointDto origin = routeWaypoints.get(0);
        SimulatorWaypointDto nextStop = routeWaypoints.size() > 1 ? routeWaypoints.get(1) : origin;
        double initialHeading = mathService.calculateBearingDegrees(
                origin.latitude(), origin.longitude(), nextStop.latitude(), nextStop.longitude(), 0.0
        );
        double initialOdometer = vehicle.odometerKm() != null ? vehicle.odometerKm() : 0.0;

        SimulatorWorkerState state = new SimulatorWorkerState(
                currentTenant(),
                targetVehicleId,
                vehicle.licensePlate(),
                vehicle.make() + " " + vehicle.model(),
                vehicle.status(),
                tripId,
                routeWaypoints,
                tickInterval,
                speedMultiplier,
                baseSpeedKmh,
                origin.latitude(),
                origin.longitude(),
                baseSpeedKmh,
                initialHeading,
                initialOdometer
        );
        state.simulatorStatus = "RUNNING";
        simulatorSessions.put(targetVehicleId, state);

        // Record & broadcast initial simulated telemetry ping at origin
        persistAndBroadcastTick(state, origin.label());

        // Schedule controlled background ticks
        scheduleWorkerTask(state);

        return toSimulatorSessionDto(state);
    }

    @Transactional
    public SimulatorSessionDto pauseSimulation(Long vehicleId) {
        SimulatorWorkerState state = getRequiredSession(vehicleId);
        cancelScheduledTaskForVehicle(vehicleId);
        state.simulatorStatus = "PAUSED";
        state.speedKmh = 0.0;
        state.lastUpdatedAt = Instant.now();
        return toSimulatorSessionDto(state);
    }

    @Transactional
    public SimulatorSessionDto resumeSimulation(Long vehicleId) {
        SimulatorWorkerState state = getRequiredSession(vehicleId);
        cancelScheduledTaskForVehicle(vehicleId);
        state.simulatorStatus = "RUNNING";
        state.speedKmh = state.baseSpeedKmh;
        state.lastUpdatedAt = Instant.now();
        scheduleWorkerTask(state);
        return toSimulatorSessionDto(state);
    }

    @Transactional
    public SimulatorSessionDto stopSimulation(Long vehicleId) {
        SimulatorWorkerState state = getRequiredSession(vehicleId);
        cancelScheduledTaskForVehicle(vehicleId);
        state.simulatorStatus = "STOPPED";
        state.speedKmh = 0.0;
        state.lastUpdatedAt = Instant.now();
        return toSimulatorSessionDto(state);
    }

    /**
     * Deterministically advances a simulated vehicle by one tick along its waypoint trajectory.
     */
    @Transactional
    public SimulatorSessionDto stepSimulation(Long vehicleId) {
        SimulatorWorkerState state = getRequiredSession(vehicleId);
        advanceWorkerOneTick(state);
        return toSimulatorSessionDto(state);
    }

    public boolean isTaskScheduledForVehicle(Long vehicleId) {
        ScheduledFuture<?> future = scheduledTasks.get(vehicleId);
        return future != null && !future.isCancelled() && !future.isDone();
    }

    public int getActiveScheduledTaskCount() {
        int count = 0;
        for (ScheduledFuture<?> f : scheduledTasks.values()) {
            if (f != null && !f.isCancelled() && !f.isDone()) {
                count++;
            }
        }
        return count;
    }

    @Transactional(readOnly = true)
    public List<SimulatorSessionDto> getSimulatorSessions() {
        List<SimulatorSessionDto> list = new ArrayList<>();
        Set<Long> seenVehicleIds = new HashSet<>();

        Long tenantId = currentTenant();
        for (SimulatorWorkerState state : simulatorSessions.values()) {
            if (Objects.equals(state.tenantId, tenantId)) {
                seenVehicleIds.add(state.vehicleId);
                list.add(toSimulatorSessionDto(state));
            }
        }

        // Also include latest persisted telemetry for vehicles not currently in simulatorSessions
        List<TrackingLog> latestPings = trackingRepository.findLatestPingPerVehicle(tenantId);
        for (TrackingLog ping : latestPings) {
            if (!seenVehicleIds.contains(ping.getVehicleId())) {
                seenVehicleIds.add(ping.getVehicleId());
                Optional<VehicleSummaryDto> vOpt = vehicleLookupService.findVehicleSummaryById(ping.getVehicleId());
                String plate = vOpt.map(VehicleSummaryDto::licensePlate).orElse("VEH-" + ping.getVehicleId());
                String makeModel = vOpt.map(v -> v.make() + " " + v.model()).orElse("Fleet Asset");
                String vStatus = vOpt.map(VehicleSummaryDto::status).orElse("AVAILABLE");
                Long tripId = ping.getTripId() != null
                        ? ping.getTripId()
                        : readRepository.findActiveTripIdForVehicle(ping.getVehicleId()).orElse(null);
                Optional<TripSummaryDto> tOpt = tripId != null ? tripLookupService.findTripSummaryById(tripId) : Optional.empty();
                List<ShipmentSummaryDto> shipments = tripId != null
                        ? shipmentLookupService.findShipmentsByTripId(tripId)
                        : Collections.emptyList();

                list.add(new SimulatorSessionDto(
                        ping.getVehicleId(),
                        plate,
                        makeModel,
                        vStatus,
                        tripId,
                        tOpt.map(TripSummaryDto::tripCode).orElse(null),
                        tOpt.map(TripSummaryDto::status).orElse(null),
                        "IDLE",
                        ping.getLatitude(),
                        ping.getLongitude(),
                        ping.getSpeedKmh(),
                        ping.getHeading(),
                        ping.getCurrentOdometerKm(),
                        0,
                        1,
                        0.0,
                        2,
                        1.0,
                        true,
                        "SIMULATED_GPS_TELEMETRY",
                        ping.getRecordedAt(),
                        List.of(new SimulatorWaypointDto(ping.getLatitude(), ping.getLongitude(), ping.getWaypointLabel())),
                        shipments
                ));
            }
        }
        return list;
    }

    @Transactional
    public TelemetryPingDto ingestSimulatedTelemetry(TelemetryPingDto ping) {
        if (ping == null || ping.vehicleId() == null) {
            throw new DomainException("Telemetry ping and vehicleId are required.", HttpStatus.BAD_REQUEST, "INVALID_TELEMETRY_PING");
        }
        Instant timestamp = ping.timestamp() != null ? ping.timestamp() : Instant.now();
        Double speed = ping.speedKmh() != null ? ping.speedKmh() : 0.0;
        mathService.validateTelemetryInputs(ping.latitude(), ping.longitude(), speed, timestamp);

        Long tenantId = currentTenant();
        Optional<TrackingLog> previousLogOpt = trackingRepository.findFirstByVehicleIdAndTenantIdOrderByRecordedAtDesc(ping.vehicleId(), tenantId);
        double computedHeading = ping.heading() != null ? ping.heading() : 0.0;
        double odometerKm = ping.currentOdometerKm() != null ? ping.currentOdometerKm() : 0.0;

        if (previousLogOpt.isPresent()) {
            TrackingLog prev = previousLogOpt.get();
            double deltaKm = mathService.haversineDistanceKm(
                    prev.getLatitude(), prev.getLongitude(),
                    ping.latitude(), ping.longitude()
            );
            computedHeading = mathService.calculateBearingDegrees(
                    prev.getLatitude(), prev.getLongitude(),
                    ping.latitude(), ping.longitude(),
                    prev.getHeading() != null ? prev.getHeading() : 0.0
            );
            if (odometerKm <= 0.0 && prev.getCurrentOdometerKm() != null) {
                odometerKm = Math.round((prev.getCurrentOdometerKm() + deltaKm) * 100.0) / 100.0;
            }
        }

        TrackingLog entity = new TrackingLog();
        entity.setTenantId(tenantId);
        entity.setVehicleId(ping.vehicleId());
        entity.setTripId(ping.tripId());
        entity.setLatitude(ping.latitude());
        entity.setLongitude(ping.longitude());
        entity.setSpeedKmh(speed);
        entity.setHeading(computedHeading);
        entity.setCurrentOdometerKm(odometerKm);
        entity.setSimulated(true);
        entity.setWaypointLabel(ping.waypointLabel());
        entity.setRecordedAt(timestamp);
        trackingRepository.save(entity);

        enforceTelemetryRetention(ping.vehicleId(), tenantId);

        String vehicleLabel = vehicleLookupService.findVehicleSummaryById(ping.vehicleId())
                .map(VehicleSummaryDto::licensePlate)
                .orElse("Vehicle #" + ping.vehicleId());
        evaluateGeofencesAndSpeed(tenantId, ping.vehicleId(), vehicleLabel, ping.latitude(), ping.longitude(), speed, timestamp);

        TelemetryPingDto enriched = new TelemetryPingDto(
                ping.vehicleId(),
                ping.tripId(),
                ping.latitude(),
                ping.longitude(),
                speed,
                computedHeading,
                odometerKm,
                timestamp,
                true,
                ping.waypointLabel(),
                "SIMULATED_GPS_TELEMETRY"
        );
        broadcastTelemetry(enriched);
        return enriched;
    }

