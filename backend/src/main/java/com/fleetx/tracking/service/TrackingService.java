    @PreDestroy
    public void shutdownSimulator() {
        for (ScheduledFuture<?> future : scheduledTasks.values()) {
            if (future != null) {
                future.cancel(false);
            }
        }
        scheduledTasks.clear();
        simulatorExecutor.shutdownNow();
    }

