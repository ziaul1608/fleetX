    @Transactional
    public void evaluateGeofencesAndSpeed(
            Long tenantId,
            Long vehicleId,
            String vehicleLabel,
            double latitude,
            double longitude,
            double speedKmh,
            Instant timestamp
    ) {
        // 1. Evaluate global overspeed violation
        if (speedKmh > defaultSpeedLimitKmh) {
            publishAlertInternal(
                    tenantId,
                    "OVERSPEED",
                    speedKmh > defaultSpeedLimitKmh + 20.0 ? "CRITICAL" : "WARNING",
                    "VEHICLE",
                    vehicleId,
                    null,
                    String.format(Locale.US,
                            "Vehicle %s exceeded speed threshold at %.1f km/h (limit: %.1f km/h).",
                            vehicleLabel, speedKmh, defaultSpeedLimitKmh),
                    timestamp
            );
        }

        // 2. Evaluate active circular and polygonal geofences
        List<Geofence> activeGeofences = geofenceRepository.findByTenantIdAndActiveTrueOrderByIdAsc(tenantId);
        for (Geofence fence : activeGeofences) {
            boolean currentlyInside = isCoordinateInsideGeofence(latitude, longitude, fence);

            // Zone speed limit check when inside geofence
            if (currentlyInside && fence.getSpeedLimitKmh() != null && speedKmh > fence.getSpeedLimitKmh()) {
                publishAlertInternal(
                        tenantId,
                        "OVERSPEED",
                        "WARNING",
                        "VEHICLE",
                        vehicleId,
                        fence.getId(),
                        String.format(Locale.US,
                                "Vehicle %s exceeded zone speed limit inside '%s': %.1f km/h (limit: %.1f km/h).",
                                vehicleLabel, fence.getName(), speedKmh, fence.getSpeedLimitKmh()),
                        timestamp
                );
            }

            Optional<GeofenceVehicleState> priorStateOpt =
                    geofenceStateRepository.findByGeofenceIdAndVehicleId(fence.getId(), vehicleId);

            if (priorStateOpt.isEmpty()) {
                GeofenceVehicleState initialState = new GeofenceVehicleState();
                initialState.setGeofenceId(fence.getId());
                initialState.setVehicleId(vehicleId);
                initialState.setInside(currentlyInside);
                initialState.setUpdatedAt(timestamp);
                geofenceStateRepository.save(initialState);

                // If initial observation is already inside a RESTRICTED zone, emit entry alert once
                if (currentlyInside && "RESTRICTED".equalsIgnoreCase(fence.getFenceType())) {
                    publishAlertInternal(
                            tenantId,
                            "GEOFENCE_ENTER",
                            "WARNING",
                            "VEHICLE",
                            vehicleId,
                            fence.getId(),
                            String.format("Vehicle %s entered restricted geofence '%s'.", vehicleLabel, fence.getName()),
                            timestamp
                    );
                }
            } else {
                GeofenceVehicleState state = priorStateOpt.get();
                boolean wasInside = Boolean.TRUE.equals(state.getInside());

                if (wasInside && !currentlyInside) {
                    // Transition: INSIDE -> OUTSIDE (Geofence Exit)
                    state.setInside(false);
                    state.setUpdatedAt(timestamp);
                    geofenceStateRepository.save(state);

                    publishAlertInternal(
                            tenantId,
                            "GEOFENCE_EXIT",
                            "WARNING",
                            "VEHICLE",
                            vehicleId,
                            fence.getId(),
                            String.format("Vehicle %s exited geofence boundary '%s' (%s).",
                                    vehicleLabel, fence.getName(), fence.getFenceType()),
                            timestamp
                    );
                } else if (!wasInside && currentlyInside) {
                    // Transition: OUTSIDE -> INSIDE (Geofence Enter)
                    state.setInside(true);
                    state.setUpdatedAt(timestamp);
                    geofenceStateRepository.save(state);

                    String severity = "RESTRICTED".equalsIgnoreCase(fence.getFenceType()) ? "WARNING" : "INFO";
                    publishAlertInternal(
                            tenantId,
                            "GEOFENCE_ENTER",
                            severity,
                            "VEHICLE",
                            vehicleId,
                            fence.getId(),
                            String.format("Vehicle %s entered geofence boundary '%s' (%s).",
                                    vehicleLabel, fence.getName(), fence.getFenceType()),
                            timestamp
                    );
                }
                // Note: If wasInside == currentlyInside (e.g., vehicle remains outside across subsequent ticks),
                // no repeated alert is emitted!
            }
        }
    }

    public boolean isCoordinateInsideGeofence(double latitude, double longitude, Geofence fence) {
        if ("POLYGON".equalsIgnoreCase(fence.getShapeType()) && fence.getPolygonCoordinatesJson() != null) {
            List<List<Double>> coords = parsePolygonCoordinates(fence.getPolygonCoordinatesJson());
            if (coords.size() >= 3) {
                return mathService.isInsidePolygon(latitude, longitude, coords);
            }
        }
        return mathService.isInsideCircle(
                latitude,
                longitude,
                fence.getCenterLatitude(),
                fence.getCenterLongitude(),
                fence.getRadiusMeters()
        );
    }

    private List<List<Double>> parsePolygonCoordinates(String json) {
        if (json == null || json.isBlank()) {
            return Collections.emptyList();
        }
        try {
            return objectMapper.readValue(json, new TypeReference<List<List<Double>>>() {});
        } catch (Exception e) {
            return Collections.emptyList();
        }
    }

