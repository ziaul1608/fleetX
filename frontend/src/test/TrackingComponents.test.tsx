describe('Module 5 — Live Tracking & Intelligent Fleet Control Tower Components', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    vi.mocked(trackingApi.getControlTowerSummary).mockResolvedValue(mockSummary);
    vi.mocked(trackingApi.getSimulatorSessions).mockResolvedValue([mockSession]);
    vi.mocked(trackingApi.getGeofences).mockResolvedValue([mockGeofence]);
    vi.mocked(trackingApi.getAlerts).mockResolvedValue({
      content: [mockAlert],
      pageNumber: 0,
      pageSize: 25,
      totalElements: 1,
      totalPages: 1,
      last: true,
    });
    vi.mocked(trackingApi.getEligibleVehicles).mockResolvedValue([
      {
        id: 101,
        licensePlate: 'MH-12-TR-8899',
        make: 'Tata',
        model: 'Prima 5530',
        status: 'AVAILABLE',
      },
    ]);
  });

  it('renders ControlTowerPage with SIMULATED DATA badges, selected vehicle telemetry, linked shipment, and 2D/3D switcher', async () => {
    render(
      <MemoryRouter>
        <ControlTowerPage />
      </MemoryRouter>
    );

    const simBadges = await screen.findAllByText(/SIMULATED DATA/i);
    expect(simBadges.length).toBeGreaterThanOrEqual(1);

    expect(await screen.findByText(/SHP-2026-501/i)).toBeInTheDocument();
    expect(screen.getAllByText(/MH-12-TR-8899/i).length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText(/4\.35 km\/L/i)).toBeInTheDocument();

    // Switch to 3D Fleet Canvas view
    const btn3d = screen.getByRole('button', { name: /3D Fleet Canvas/i });
    fireEvent.click(btn3d);

    expect(
      await screen.findByTestId('three-fleet-scene')
    ).toBeInTheDocument();
  });

  it('acknowledges an operational alert and controls simulator pause/stop in ControlTowerPage', async () => {
    vi.mocked(trackingApi.acknowledgeAlert).mockResolvedValue({
      ...mockAlert,
      acknowledged: true,
      acknowledgedBy: 'admin@fleetx.com',
    });
    vi.mocked(trackingApi.pauseSimulation).mockResolvedValue({
      ...mockSession,
      simulatorStatus: 'PAUSED',
      speedKmh: 0,
    });

    render(
      <MemoryRouter>
        <ControlTowerPage />
      </MemoryRouter>
    );

    const ackBtn = await screen.findByRole('button', { name: /Acknowledge/i });
    fireEvent.click(ackBtn);

    await waitFor(() => {
      expect(trackingApi.acknowledgeAlert).toHaveBeenCalledWith(77);
    });

    const pauseBtn = screen.getByRole('button', { name: /Pause/i });
    fireEvent.click(pauseBtn);

    await waitFor(() => {
      expect(trackingApi.pauseSimulation).toHaveBeenCalledWith(101);
    });
  });

  it('validates and creates a polygonal geofence in CreateGeofenceModal', async () => {
    vi.mocked(trackingApi.createGeofence).mockResolvedValue({
      ...mockGeofence,
      id: 2,
      name: 'Chakan Polygon Hub',
      shapeType: 'POLYGON',
    });

    const onCreated = vi.fn();
    render(
      <CreateGeofenceModal
        isOpen={true}
        onClose={vi.fn()}
        onCreated={onCreated}
      />
    );

    const nameInput = screen.getByPlaceholderText(/e\.g\., Central Depot Mumbai/i);
    fireEvent.change(nameInput, { target: { value: 'Chakan Polygon Hub' } });

    const submitBtn = screen.getByRole('button', { name: /Save Geofence/i });
    fireEvent.click(submitBtn);

    await waitFor(() => {
      expect(trackingApi.createGeofence).toHaveBeenCalledTimes(1);
      expect(onCreated).toHaveBeenCalled();
    });
  });

  it('renders ReportsPage with persisted database rows and meaningful empty state when empty', async () => {
    vi.mocked(trackingApi.getReportSummary).mockResolvedValueOnce({
      reportType: 'TRIPS',
      startDate: null,
      endDate: null,
      statusFilter: null,
      totalRecords: 0,
      columns: ['trip_code', 'vehicle_plate', 'status'],
      rows: [],
      generatedAt: '2026-10-13T10:00:00Z',
    });

    render(
      <MemoryRouter>
        <ReportsPage />
      </MemoryRouter>
    );

    expect(
      await screen.findByText(/No persisted records found in the database/i)
    ).toBeInTheDocument();
  });

  it('renders 2D Live Map, 3D Fleet Canvas, Telemetry Table, and Reports buttons with white high-visibility styling', async () => {
    vi.mocked(trackingApi.getControlTowerSummary).mockResolvedValue(mockSummary);
    vi.mocked(trackingApi.getSimulatorSessions).mockResolvedValue([mockSession]);
    vi.mocked(trackingApi.getAlerts).mockResolvedValue({
      content: [],
      pageNumber: 0,
      pageSize: 25,
      totalElements: 0,
      totalPages: 0,
      last: true,
    });
    vi.mocked(trackingApi.getGeofences).mockResolvedValue([]);

    render(
      <MemoryRouter>
        <ControlTowerPage />
      </MemoryRouter>
    );

    const btn2D = await screen.findByRole('button', { name: /2D Live Map/i });
    const btn3D = screen.getByRole('button', { name: /3D Fleet Canvas/i });
    const btnTable = screen.getByRole('button', { name: /Telemetry Table/i });
    const btnReports = screen.getByRole('link', { name: /Reports & CSV Export/i });

    expect(btn2D).toBeInTheDocument();
    expect(btn3D).toBeInTheDocument();
    expect(btnTable).toBeInTheDocument();
    expect(btnReports).toBeInTheDocument();

    expect(btn2D.className).toContain('text-white');
    expect(btn3D.className).toContain('text-white');
    expect(btnTable.className).toContain('text-white');
    expect(btnReports.className).toContain('text-white');
  });
});
